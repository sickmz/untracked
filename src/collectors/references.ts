import { stat } from 'node:fs/promises'
import { basename, join } from 'node:path'
import { hashFile, readHead, tilde } from '../lib/fs'
import type { Context, Item } from '../types'
import { ASSIGNMENT, BUILTINS, expandPath, KEYWORDS, present, splitCommands, splitWords } from './shell'

const CONFIG_LIMIT = 4 * 1024 * 1024
const INTERPRETERS = new Set(['bash', 'sh', 'zsh', 'node', 'bun', 'python', 'python3'])
const SHELLS = new Set(['bash', 'sh', 'zsh'])
// "-c", "-lc", "-ec": the next word is a command line.
const SHELL_COMMAND = /^-[A-Za-z]*c$/
const LAUNCHERS = new Set(['env', 'exec', 'nohup'])
// Launcher options whose value is the next word: "env -u NAME", "env -C DIR", "exec -a NAME".
const LAUNCHER_VALUES = new Set(['-u', '-C', '-S', '-a', '--unset', '--chdir', '--split-string'])
const EVENT_NAME = /^[\w.-]+$/
const SAFE_SUBJECT = /^[\w./~${}@+:,=-]+$/
// A path written with ordinary characters only: no scheme, no query, no option value.
const PLAIN_PATH = /^[\w./~${}@+-]+$/
const SCRIPT_EXTENSION = /\.(?:sh|bash|zsh|js|mjs|cjs|ts|py|rb|pl|php)$/
const MARKER = /\b(?:installed|managed|generated) by ([\w.-]+)/i
// Words that follow "generated by" in prose and are never a program.
const NOT_TOOLS = new Set(['a', 'an', 'the', 'this', 'hand', 'default'])
const NO_VARS = new Map<string, string>()

type Reference = {
  // The configured command, or for core.hooksPath the configured path.
  command: string
  event: string | null
}

export async function collectReferences(ctx: Context): Promise<Item[]> {
  const groups = await Promise.all([
    claudeSettings(ctx),
    codexHooks(ctx),
    gitConfig(ctx, '.gitconfig'),
    gitConfig(ctx, '.config/git/config'),
  ])
  const items = new Map<string, Item>()
  for (const item of groups.flat()) items.set(item.id, item)
  return [...items.values()]
}

async function claudeSettings(ctx: Context): Promise<Item[]> {
  const file = join(ctx.home, '.claude/settings.json')
  const settings = await readJson(file)
  if (!isRecord(settings)) return []
  const references = findCommands(settings.hooks, 'hooks', null)
  const status_line = settings.statusLine
  if (isRecord(status_line) && typeof status_line.command === 'string') {
    references.push({ command: status_line.command, event: 'statusLine' })
  }
  return resolveAll(ctx, file, references)
}

async function codexHooks(ctx: Context): Promise<Item[]> {
  const file = join(ctx.home, '.codex/hooks.json')
  const hooks = await readJson(file)
  if (hooks == null) return []
  return resolveAll(ctx, file, findCommands(hooks, 'hooks', null))
}

// Null when the file is missing, unreadable or not valid JSON.
async function readJson(file: string): Promise<unknown> {
  if (!(await isFile(file))) return null
  try {
    return JSON.parse(await readHead(file, CONFIG_LIMIT))
  } catch {
    return null
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

async function isFile(file: string): Promise<boolean> {
  try {
    return (await stat(file)).isFile()
  } catch {
    return false
  }
}

// Every "command" string in a JSON tree. A key directly under a "hooks" object names the event.
function findCommands(value: unknown, parent: string, event: string | null): Reference[] {
  if (Array.isArray(value)) return value.flatMap((child) => findCommands(child, parent, event))
  if (!isRecord(value)) return []
  return Object.entries(value).flatMap(([key, child]) => {
    if (key === 'command' && typeof child === 'string') return [{ command: child, event }]
    const next = parent === 'hooks' && key !== 'hooks' && EVENT_NAME.test(key) ? key : event
    return findCommands(child, key, next)
  })
}

async function gitConfig(ctx: Context, relative: string): Promise<Item[]> {
  const file = join(ctx.home, relative)
  if (!(await isFile(file))) return []
  const hooks_path = hooksPath(await readHead(file, CONFIG_LIMIT))
  if (hooks_path == null) return []
  const label = tilde(ctx.home, file)
  const resolved = expandPath(hooks_path, ctx.home, NO_VARS)
  const shown = resolved == null ? hooks_path : tilde(ctx.home, resolved)
  if (!SAFE_SUBJECT.test(shown)) return []
  const item: Item = {
    id: `hook:${label}:core.hooksPath:${shown}`,
    kind: 'hook',
    category: 'manual',
    name: basename(shown),
    detail: `${label} sets core.hooksPath to ${shown}`,
    path: label,
    fingerprint: '',
  }
  if (resolved != null && !(await present(resolved))) {
    item.category = 'orphan'
    item.detail = `names ${shown}, which is missing`
  }
  return [item]
}

// The last core.hooksPath value of a git config file.
function hooksPath(text: string): string | null {
  let section = ''
  let found: string | null = null
  for (const raw of text.split('\n')) {
    const line = raw.trim()
    const header = line.match(/^\[\s*([\w.-]+)\s*("[^"]*")?\s*\]/)
    if (header != null) {
      section = header[2] == null ? (header[1] ?? '').toLowerCase() : ''
      continue
    }
    if (section !== 'core') continue
    const entry = line.match(/^hookspath\s*=\s*(.*)$/i)
    if (entry != null) found = gitValue(entry[1] ?? '')
  }
  return found
}

function gitValue(raw: string): string {
  if (raw.startsWith('"')) {
    const end = raw.indexOf('"', 1)
    return end < 0 ? raw.slice(1) : raw.slice(1, end)
  }
  return raw.replace(/\s*[#;].*$/, '').trim()
}

async function resolveAll(ctx: Context, file: string, references: Reference[]): Promise<Item[]> {
  const items = await Promise.all(references.map((reference) => resolveHook(ctx, file, reference)))
  return items.filter((item) => item != null)
}

async function resolveHook(ctx: Context, file: string, reference: Reference): Promise<Item | null> {
  const subject = await findSubject(ctx, reference.command)
  if (subject == null) return null
  const label = tilde(ctx.home, file)
  const is_path = isPath(subject)
  const resolved = is_path ? expandPath(subject, ctx.home, NO_VARS) : null
  const shown = resolved == null ? subject : tilde(ctx.home, resolved)
  const name = basename(shown)
  const event = reference.event
  const item: Item = {
    id: event == null ? `hook:${label}:${shown}` : `hook:${label}:${event}:${shown}`,
    kind: 'hook',
    category: 'manual',
    name,
    detail: `${label} runs ${shown}${occasion(event)}`,
    path: label,
    fingerprint: '',
  }
  if (!is_path) {
    if ((await ctx.which(subject)) == null) {
      item.category = 'orphan'
      item.detail = `names ${name}, which is missing`
    }
    return item
  }
  if (resolved == null) return item
  if (!(await present(resolved))) {
    item.category = 'orphan'
    item.detail = `names ${shown}, which is missing`
    return item
  }
  if (!(await isFile(resolved))) return item
  if (resolved.startsWith(`${ctx.home}/`)) item.fingerprint = await hashFile(resolved)
  const owner = findOwner(await readHead(resolved, 8192))
  if (owner != null && (await ctx.which(owner)) == null && (await ctx.which(owner.toLowerCase())) == null) {
    item.category = 'orphan'
    item.detail = `left by ${owner}, which is not installed`
  }
  return item
}

function occasion(event: string | null): string {
  if (event == null) return ''
  if (event === 'statusLine') return ' for its status line'
  return ` on ${event}`
}

// The script a command runs when there is one, else the program. Never one of its arguments.
// Simple commands that only run builtins ("cd x && ./run.sh") are passed over.
async function findSubject(ctx: Context, command: string): Promise<string | null> {
  for (const words of splitCommands(splitWords(command))) {
    const subject = await commandSubject(ctx, words)
    if (subject != null) return subject
  }
  return null
}

async function commandSubject(ctx: Context, words: string[]): Promise<string | null> {
  let index = 0
  while (index < words.length) {
    const word = words[index] ?? ''
    if (ASSIGNMENT.test(word) || KEYWORDS.has(word)) {
      index++
      continue
    }
    if (!LAUNCHERS.has(basename(word))) break
    index++
    while ((words[index] ?? '').startsWith('-')) {
      index += LAUNCHER_VALUES.has(words[index] ?? '') ? 2 : 1
    }
  }
  const program = words[index]
  if (program == null || BUILTINS.has(program)) return null
  if (!(await isProgram(ctx, program))) return null
  const interpreter = basename(program)
  if (!INTERPRETERS.has(interpreter)) return program
  for (const [offset, word] of words.slice(index + 1).entries()) {
    if (SHELLS.has(interpreter) && SHELL_COMMAND.test(word)) {
      return (await findSubject(ctx, words[index + offset + 2] ?? '')) ?? program
    }
    if (word === '-c' || word === '-e' || word === '-m') return program
    if (await isScript(ctx, word)) return word
  }
  return program
}

// A word in command position that may be shown: a bare name or plain path, or a file that exists.
async function isProgram(ctx: Context, word: string): Promise<boolean> {
  if (PLAIN_PATH.test(word)) return true
  return isExisting(ctx, word)
}

// A word after an interpreter that is the script it runs: a plain path ending in a script extension,
// or a file that exists. Anything else may be an option's value and is never shown.
async function isScript(ctx: Context, word: string): Promise<boolean> {
  if (word.startsWith('-')) return false
  if (PLAIN_PATH.test(word) && SCRIPT_EXTENSION.test(word)) return true
  return isExisting(ctx, word)
}

async function isExisting(ctx: Context, word: string): Promise<boolean> {
  if (!SAFE_SUBJECT.test(word)) return false
  const resolved = expandPath(word, ctx.home, NO_VARS)
  return resolved != null && (await isFile(resolved))
}

// A subject that names a file rather than a program on PATH.
function isPath(word: string): boolean {
  return word.includes('/') || word.startsWith('~') || word.startsWith('$') || SCRIPT_EXTENSION.test(word)
}

// The tool a script's header says put it there: "installed by X", "managed by X", "generated by X".
function findOwner(head: string): string | null {
  for (const line of head.split('\n').slice(0, 15)) {
    const owner = line.match(MARKER)?.[1]?.replace(/[.-]+$/, '')
    if (owner == null || owner === '' || NOT_TOOLS.has(owner.toLowerCase())) continue
    return owner
  }
  return null
}
